-- =============================================================================
-- support_db V3 — ticket.title
--
-- 工单标题此前没有落点:创建接口收到 title 后,只有在 message 为空时才把它当作
-- 首条消息,同时提交 title 与 message 时标题被直接丢弃。控制台列表展示的"标题"
-- 其实是首条消息的正文。标题是客户填写的一行概要,与会话正文是两回事,按事实
-- 单独存一列;老工单为 NULL,前端回退显示首条消息。
--
-- 宽度 128 字符(utf8mb4 按字符计),服务端创建时按同一上限校验,超长返回 400
-- 而不是落库失败。
-- =============================================================================

ALTER TABLE `ticket`
  ADD COLUMN `title` VARCHAR(128) DEFAULT NULL
    COMMENT '工单标题(客户填写的一行概要);老数据为 NULL,展示回退到首条消息' AFTER `category`;
